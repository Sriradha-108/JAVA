

public class Rela {
    public static void main(String[] args){
        // Relational operator --> ==, !=, <, >, <=, >=
        int a = 5;
        int b =10;

        boolean c = (a == b); //F
        System.out.println(c);

        boolean d = (a != b); //True
        System.out.println(d);

        boolean e = (a < b); //t
        System.out.println(e);

        boolean f = (a > b); //false
        System.out.println(f);


    }
}